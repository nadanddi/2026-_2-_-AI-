def get_said(e):
    i = e.index("[말할 것] ") + len("[말할 것] ")
    return e[i: e.index("\\n\\n", i)]


def set_said(e, said):
    i = e.index("[말할 것] ")
    j = e.index("\\n\\n", i)
    return e[:i] + "[말할 것] " + said + e[j:]


def drop_said(e):
    i = e.index("[말할 것] ")
    j = e.index("\\n\\n", i)
