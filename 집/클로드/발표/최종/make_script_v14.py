# 연구실 대본 v13을 집 최종 덱(팜모니_발표자료_집v1.pptx)에 맞춘 대본 v14로 만든다 (2026-11-04, 집 클로드)
# 바꾸는 것: 결과 요약 장 삭제와 장 번호 당김, 시간표, 기준 덱, 연구실 반영대기 목록 3·4(질의응답, 말하지 말 것).
# 그 뒤 덱 노트의 [말할 것]과 대본 대사가 글자 단위로 같은지 확인한다.
import re
import sys

from pptx import Presentation

SRC = "연구실/클로드/발표/발표대본_G05v17_최종_v13_2026-11-04.md"
OUT = "집/클로드/발표/최종/발표대본_집v1_최종_v14_2026-11-04.md"
DECK = "집/클로드/발표/최종/팜모니_발표자료_집v1.pptx"

s = open(SRC, encoding="utf-8").read()


def rep(old, new):
    global s
    if s.count(old) != 1:
        sys.exit(f"원문 {s.count(old)}곳: {old[:50]!r}")
    s = s.replace(old, new)


rep("# 팜모니 발표 대본 — 최종 v13 (2026-11-04, 연구실 클로드)\n",
    "# 팜모니 발표 대본 — 최종 v14 (2026-11-04, 집 클로드)\n\n"
    "- v13에서 바뀐 것: 기준 덱 **집 최종 v1**(`집/클로드/발표/최종/팜모니_발표자료_집v1.pptx`, 연구실 G05v19 + 사용자 적용 대기 목록). "
    "결과 요약 장을 빼서 본문 16장(최종 점수는 1.8 표 캡션과 노트로), 장 번호를 하나씩 당김. "
    "연구실 반영대기 목록 3·4(질의응답 4~5개, 말하지 말 것 3개)를 넣음. 대사는 결과 요약 장을 뺀 것 말고는 v13과 같음.\n")
rep("덱 본문은 17장.", "덱 본문은 16장.")
rep("- 기준 덱: `연구실/클로드/발표/덱/팜모니AI_발표자료_G05v17.pptx` 본문 1~17장",
    "- 기준 덱: `집/클로드/발표/최종/팜모니_발표자료_집v1.pptx` 본문 1~16장")

# 시간표: 결과 요약 0:26을 뺌
rep("- 표지 0:29 · 결과 요약 0:26 → 누적 0:55\n", "- 표지 0:29 → 누적 0:29\n")
rep("→ 누적 6:26", "→ 누적 6:00")
rep("→ 누적 8:41", "→ 누적 8:15")
rep("→ 누적 9:35", "→ 누적 9:09")
rep("합계 9:35, 넘김을 1~2초로 보면 9분 27~43초.", "합계 9:09, 넘김을 1~2초로 보면 9분 01~17초(결과 요약 장 0:26을 뺌).")
s = s.replace("≈ 9분 27~43초(10분 안, 목표 9분 20초보다 길 수 있음)", "≈ 9분 01~17초(결과 요약 장을 빼서 목표 9분 20초 안)")

# 결과 요약 장 절 삭제, 장 번호 당김
m = re.search(r"## 2\. 결과 요약 \(0:26\)\n.*?(?=\n## 3\. )", s, re.S)
if not m:
    sys.exit("결과 요약 절을 찾지 못함")
s = s[: m.start()] + s[m.end() + 1:]
s = re.sub(r"^## (\d+)\. ", lambda mm: f"## {int(mm.group(1)) - 1}. " if int(mm.group(1)) >= 3 else mm.group(0), s, flags=re.M)

# 덧붙일 문장: 결과 요약 장 문장을 표지 끝으로
rep('- 2장: "매 시각 이만큼 틀린다는 뜻이 아니라 평균적인 크기입니다." / ',
    '- 표지 끝(결과 요약 장을 빼서 점수를 말로 넣고 싶을 때): "최종 점수는 배지 온도 오차 0.46도, EC 0.11, 이미지 정답률 97%였습니다." / ')

# 질의응답(연구실 반영대기 3)
QA = """
- **"설명력 −0.64는 음의 상관인가?"** 아닙니다. 교차검증 결정계수(설명력)입니다. 평균값으로 찍는 것보다 못 맞히면 음수가 됩니다. · 1.3
- **"추운 조건 보정 값은 이 데이터에만 맞는 것 아닌가?"** 숫자(0.25℃, EC 0.8~1.2)는 F13·F47 학습 정답에서 쟀습니다. 옮길 수 있는 것은 방법이고, 현장에서는 그 농장 자료로 다시 재야 합니다. 효과는 작고, 핵심 성능은 전날 보정에서 나옵니다. · 1.5 노트
- **"EC 예측이 틀리면 온도도 틀리나?"** 검증할 때부터 EC 실측이 아니라 EC 예측으로 쟀습니다. 추운 시간에만, 최대 0.25℃까지 붙습니다. · 1.5 노트
- **"모델 C는 무엇인가?"** 공개 사전학습 모델(TabPFN v2)에 우리 학습 기록을 예시로 보여 주고 추정합니다. 우리 자료로 재학습하지 않았습니다. · 1.4 노트
- (선택) **"실내 온도로 비중을 왜 바꾸나?"** C는 학습 범위 밖 추위에서 크게 틀렸습니다. 8℃ 이하 추운 날 검증에서 C만 쓰면 오차 2.35~2.45℃, B만 쓰면 0.94℃였습니다(카탈로그 6.67). 따뜻할 때는 C가 도움이 되어 빼면 보통 날 검증이 약 3% 나빠집니다. 문턱을 6~8℃, 7~9℃로 바꿔도 결과가 비슷했고, 다른 온실 32곳 중 28곳에서 같은 방향이었습니다(6.69·6.70·6.75). 문턱은 현장 자료로 다시 정해야 합니다. · 1.4
"""
rep("\n### 나. 답이 약한 질문 10개", QA + "\n### 나. 답이 약한 질문 10개")

# 말하지 말 것(연구실 반영대기 4)
rep('- "다른 온실 자료는 쓰지 않았다" → 최종 모델 학습에만 안 썼고, 시험·확인에는 씀.\n',
    '- "다른 온실 자료는 쓰지 않았다" → 최종 모델 학습에만 안 썼고, 시험·확인에는 씀.\n'
    '- "음의 상관" → 설명력(교차검증 결정계수)이다.\n'
    '- "모델 C는 우리 자료로 학습했다" → 공개 사전학습 모델에 예시만 보여 줌, 재학습 없음.\n'
    '- "비슷한 기록의 온도를 그대로 가져온다" → 예시 전체의 관계를 읽어 계산함.\n')

# ---- 덱 노트와 대조 ----
said = {}
for blk in re.split(r"\n(?=## \d+\. )", s):
    mm = re.match(r"## (\d+)\. [^\n]*\n(.*)", blk, re.S)
    if not mm:
        continue
    lines = []
    for ln in mm.group(2).split("\n"):
        if ln.startswith("- ") or ln.startswith("---") or ln.startswith("## "):
            break
        if ln.strip():
            lines.append(ln.strip())
    said[int(mm.group(1))] = " ".join(lines).replace("**", "")

prs = Presentation(DECK)
bad = 0
for i, sl in enumerate(prs.slides, 1):
    if i > 16:
        break
    note = sl.notes_slide.notes_text_frame.text if sl.has_notes_slide else ""
    m2 = re.search(r"\[말할 것\] (.*?)(\n|$)", note)
    deck_said = m2.group(1).strip() if m2 else ""
    if deck_said != said.get(i, None):
        bad += 1
        print("불일치", i, deck_said[:40], "|", (said.get(i) or "")[:40])
print(f"대조: 본문 {min(16, len(prs.slides))}장, 불일치 {bad}")

s = s.rstrip() + f"\n\n## 대조 기록(집 v1, 2026-11-04)\n- 덱 `팜모니_발표자료_집v1.pptx` 본문 1~16장 노트의 [말할 것]과 이 대본 각 장 대사(굵은 표시 `**`만 뺀 글자)를 PPTX에서 꺼내 비교: 불일치 {bad}.\n"
open(OUT, "w", encoding="utf-8").write(s)
print("wrote", OUT)
