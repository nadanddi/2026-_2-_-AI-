def notes_expr(block):
    m = re.search(r"\n  s\.addNotes\((.*)\);\n", block)
    need(m, "노트 줄")
    return m.group(1)


def set_said(expr, said):
    """노트 식의 [말할 것] 문장을 바꾼다(said=None이면 [말할 것] 머리를 다른 이름표로)."""
    i = expr.index("[말할 것] ")
    j = expr.index("\\n\\n", i)
    if said is None:
        return expr[:i] + "[옛 대사]" + expr[i + len("[말할 것]"):j] + expr[j:]
    return expr[:i] + "[말할 것] " + said + expr[j:]


def get_said(expr):
    i = expr.index("[말할 것] ") + len("[말할 것] ")
    return expr[i: expr.index("\\n\\n", i)]


def drop_said(expr):
    """합치는 장의 대사 부분은 지우고 나머지 노트만 남긴다."""
    i = expr.index("[말할 것] ")
    j = expr.index("\\n\\n", i)
    return expr[:i] + expr[j + 4:]


def js(t):
    return t.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


